const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const electronModule = require.resolve('electron');
require.cache[electronModule] = { id: electronModule, filename: electronModule, loaded: true, exports: { dialog: {}, shell: {} } };
const { registerHandlers } = require('../electron/ipc/register-handlers.cjs');
const { YouTubeService } = require('../electron/services/youtube.cjs');

test('IPC rejects unanalysed identities and derives media flags from the analysed format', async (t) => {
  const dir = await fs.promises.mkdtemp(path.join(os.tmpdir(), 'video-studio-ipc-'));
  t.after(() => fs.promises.rm(dir, { recursive: true, force: true }));
  const originalAnalyze = YouTubeService.prototype.analyze;
  const originalDownload = YouTubeService.prototype.download;
  t.after(() => { YouTubeService.prototype.analyze = originalAnalyze; YouTubeService.prototype.download = originalDownload; });
  const format = { id: '137', hasVideo: true, hasAudio: false, quickTimeCompatible: false, ext: 'webm', fileSizeBytes: 1000 };
  YouTubeService.prototype.analyze = async () => ({ id: 'video-a', formats: [format] });
  let received;
  YouTubeService.prototype.download = async payload => { received = payload; return { ok: true, outputPath: path.join(dir, 'result.mp4') }; };
  const handlers = new Map();
  const root = path.resolve(__dirname, '..');
  const sender = { isDestroyed: () => false, send: () => {} };
  const event = { sender, senderFrame: { url: pathToFileURL(path.join(root, 'dist', 'index.html')).href } };
  registerHandlers({ app: { getAppPath: () => root, getPath: () => dir }, ipcMain: { handle: (channel, handler) => handlers.set(channel, handler) }, dependencyService: { getFfmpegInfo: async () => ({ ffmpegPath: 'fixture' }), getYtDlpInfo: async () => ({ ytDlpPath: 'fixture' }) } });
  const download = payload => handlers.get('download:start')(event, { url: 'https://youtu.be/a', videoId: 'video-a', formatId: '137', outputDir: dir, ...payload });
  await assert.rejects(download({}), /Analyse à nouveau/);
  await handlers.get('video:analyze')(event, 'https://youtu.be/a');
  await assert.rejects(download({ url: 'https://youtu.be/b' }), /Analyse à nouveau/);
  await assert.rejects(download({ videoId: 'wrong' }), /Analyse à nouveau/);
  await assert.rejects(download({ formatId: '999' }), /Analyse à nouveau/);
  await download({ hasAudio: true, shouldRecodeToMp4: false, expectedSizeBytes: 999999 });
  assert.equal(received.hasAudio, false);
  assert.equal(received.shouldRecodeToMp4, true);
  assert.equal(received.mergeAudioIfNeeded, true);
  assert.equal(received.expectedSizeBytes, 1000);
  await assert.rejects(handlers.get('job:current')({ sender, senderFrame: { url: 'https://attacker.example/' } }), /non autorisé/);
});
